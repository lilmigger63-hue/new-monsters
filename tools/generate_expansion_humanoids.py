def grip(a,weapon,side='right',axis='y'):
    sign=1 if side=='left' else -1;ax=sign*(a.width+.75);y=a.sh-9.5;z=-1.1
    # Keep palm, replace its straight fingers with enclosed opposing digits.
    a.m.by_name['hand_'+side]['cubes']=a.m.by_name['hand_'+side]['cubes'][:3]
    socket='grip_'+side;a.bone(socket,'hand_'+side,(ax,y,z))
    if weapon not in a.m.by_name:a.bone(weapon,socket,(ax,y,z))
    else:a.m.by_name[weapon]['parent']=socket
    for k in range(3):
        if axis=='y':
            yy=y-1+k*.67
            a.box(socket,(ax-1.15,yy,z-1),(1.85,.5,.65),0)
            a.box(socket,(ax+.55,yy,z-.9),(.55,.5,1.6),1)
        else:
            xx=ax-1+k*.67
            a.box(socket,(xx,y-1,z-1),(.5,1.8,.6),0)
            a.box(socket,(xx,y-1.05,z-.8),(.5,.55,1.65),1)
    a.box(socket,(ax-1.25,y+.4,z-.65),(.7,.8,1.6),1,(14,0,-sign*13))
    return ax,y,z


