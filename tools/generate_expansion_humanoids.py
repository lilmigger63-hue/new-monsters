class Sculpt:
    def __init__(self,name):
        self.name=name;self.m=Model(name)
        self.w,self.height,self.ticks,self.total,self.hip,self.sh,self.width=SPECS[name]
        self.s=self.height*16/self.total
    def bone(self,name,parent,pivot,rot=None):
        return self.m.bone(name,parent,[v*self.s for v in pivot],rot)
    def box(self,bone,origin,size,material,rot=None,pivot=None):
        self.m.box(bone,[v*self.s for v in origin],[v*self.s for v in size],material,rot,[v*self.s for v in pivot] if pivot else None)
    def facet(self,bone,origin,size,material,bevel=.14):
        x,y,z=origin;w,h,d=size;b=min(w,d)*bevel
        self.box(bone,(x+b,y,z+b),(w-b*2,h*.16,d-b*2),material)
        self.box(bone,(x,y+h*.15,z),(w,h*.7,d),material)
        self.box(bone,(x+b,y+h*.84,z+b),(w-b*2,h*.16,d-b*2),material)


