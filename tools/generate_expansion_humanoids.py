def verify(a,animations):
    vertices=model_vertices(a.m)
    assert min(p[1] for p in vertices)>-.001,'Rest geometry below ground'
    assert animations['death']['animation_length']<=.65
    for state in ('attack','heavy','cast'):
        assert str(round(a.ticks/20,4)) in animations[state]['bones']['body']['rotation'], 'Server impact landmark moved'
    # Independent dense samples of linear interpolation between support keys.
    death=animations['death']['bones']['root'];rows=sorted((float(t),v) for t,v in death['rotation'].items())
    pos=death['position'];minimum=1e6
    for (ta,ra),(tb,rb) in zip(rows,rows[1:]):
        pa=pos[str(ta)] if str(ta) in pos else pos[next(k for k in pos if float(k)==ta)]
        pb=pos[str(tb)] if str(tb) in pos else pos[next(k for k in pos if float(k)==tb)]
        for f in (.25,.5,.75):
            rot=[x+(y-x)*f for x,y in zip(ra,rb)];lift=pa[1]+(pb[1]-pa[1])*f
            minimum=min(minimum,min(rotate(p,[0,0,0],rot)[1]+lift for p in vertices))
    assert minimum>=-.001,(a.name,'death floor',minimum)
    for n,b in a.m.by_name.items():
        if n.startswith('grip_'):
            assert len(b['cubes'])==7
            for animation in animations.values():assert n not in animation['bones']
    for weapon in ('dagger','poleblade','poleaxe','khopesh','shortsword','support_marker'):
        if weapon in a.m.by_name:
            assert a.m.by_name[weapon]['parent'].startswith('grip_')
            for animation in animations.values():assert weapon not in animation['bones']
    print(f'  floor rest={min(p[1] for p in vertices):.4f}px, dense 3D death={minimum:.4f}px; rigid grips verified')


