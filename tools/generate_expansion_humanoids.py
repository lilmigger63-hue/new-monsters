def rotate(point,pivot,angles):
    x,y,z=[point[i]-pivot[i] for i in range(3)]
    for axis,angle in enumerate(angles):
        c=math.cos(math.radians(angle));s=math.sin(math.radians(angle))
        if axis==0:y,z=y*c-z*s,y*s+z*c
        elif axis==1:x,z=x*c+z*s,-x*s+z*c
        else:x,y=x*c-y*s,x*s+y*c
    return [x+pivot[0],y+pivot[1],z+pivot[2]]


def model_vertices(model):
    points=[]
    for bone in model.bones:
        for cube in bone.get('cubes',[]):
            for signs in itertools.product((0,1),repeat=3):
                point=[cube['origin'][i]+cube['size'][i]*signs[i] for i in range(3)]
                point=rotate(point,cube.get('pivot',bone['pivot']),cube.get('rotation',[0,0,0]))
                cursor=bone
                while cursor['name']!='root':
                    point=rotate(point,cursor['pivot'],cursor.get('rotation',[0,0,0]));cursor=model.by_name[cursor['parent']]
                points.append(point)
    return points


def fit_authored_height(a):
    """Fit the complete authored silhouette to its explicit species height."""
    top=max(p[1] for p in model_vertices(a.m));factor=a.height*16/top
    for bone in a.m.bones:
        bone['pivot']=[v*factor for v in bone['pivot']]
        for cube in bone.get('cubes',[]):
            for field in ('origin','size','pivot'):
                if field in cube:cube[field]=[v*factor for v in cube[field]]
    a.s*=factor


