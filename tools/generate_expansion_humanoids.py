def painted_atlas(palette,materials,translucent=False):
    """Original hand-placed brocade, chased metal, scales and hair filaments."""
    image=pipeline_base(palette,materials,translucent)
    draw=ImageDraw.Draw(image)
    for index in range(16):
        x=index%4*32;y=index//4*32
        rgb=tuple(int(palette[index][i:i+2],16) for i in (0,2,4))
        def col(delta):return tuple(max(0,min(255,k+delta)) for k in rgb)+(255,)
        if index in (3,10,15):
            # Repeating embroidered climbing-vine diamonds, intentionally sparse.
            for xx,yy in ((7,8),(21,8),(14,21)):
                draw.line([(x+xx,y+yy-3),(x+xx+3,y+yy),(x+xx,y+yy+3),(x+xx-3,y+yy),(x+xx,y+yy-3)],fill=col(23))
                draw.line((x+xx,y+yy+3,x+xx+2,y+yy+7),fill=col(13))
